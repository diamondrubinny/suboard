import type { ReactNode } from 'react';
import { Link } from 'react-router-dom';
import { useAuth } from '../../auth/AuthContext';
import { A11yToolbar } from '../../components/A11yToolbar';
import { Footer, Logo, usePageTitle } from '../../components/Layout';

const UPDATED = '10/11/2026';

/** Legal pages are public: rendered inside a minimal shell when the visitor is not signed in. */
function LegalShell({ title, children }: { title: string; children: ReactNode }) {
  usePageTitle(title);
  const { user } = useAuth();
  const body = (
    <article className="prose card">
      <div className="draft-banner" role="note">
        טיוטה טכנית — מחייבת בדיקה ואישור של יועץ משפטי / ממונה פרטיות / מורשה נגישות לפני פרסום סופי.
      </div>
      <h1>{title}</h1>
      <p className="muted">עודכן לאחרונה: {UPDATED}</p>
      {children}
    </article>
  );
  if (user && !user.mustChangePassword && !user.mfaSetupRequired) return body;
  return (
    <>
      <a href="#main" className="skip-link">
        דילוג לתוכן הראשי
      </a>
      <header className="app-header">
        <Link to="/login" className="brand">
          <Logo /> <span>SUBoard</span>
        </Link>
      </header>
      <main id="main" className="main" style={{ maxInlineSize: '900px', marginInline: 'auto' }}>
        {body}
      </main>
      <Footer />
      <A11yToolbar />
    </>
  );
}

