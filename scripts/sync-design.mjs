// Compiles the SUBoard Spectrum design system (copied into ./design from claude.ai Design) into the web app:
//   design/tokens.json  -> apps/web/src/styles/tokens.css   (custom properties, themes, @font-face)
//   design/bundle.css   -> apps/web/src/styles/global.css   (verbatim)
//   design/*.woff2      -> apps/web/src/assets/fonts/
// Run after re-downloading the design system's files:  node scripts/sync-design.mjs
import { copyFileSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const design = join(root, 'design');
const styles = join(root, 'apps/web/src/styles');
const fontsOut = join(root, 'apps/web/src/assets/fonts');
const t = JSON.parse(readFileSync(join(design, 'tokens.json'), 'utf8'));

const COLOR = /^(#[0-9a-f]{3,8}|(rgba?|hsla?|oklch|oklab|lab|lch|color)\([^()]*\))$/i;
const ALIAS = /^\{([A-Za-z0-9][A-Za-z0-9_.-]{0,63})\}$/;
const themes = t.color.themes.map((th) => th.id);
const first = themes[0];
const valueFor = (tok, theme) => (typeof tok.value === 'string' ? (theme === first ? tok.value : undefined) : tok.value[theme]);
const css = (v) => {
  const a = ALIAS.exec(v);
  if (a) return `var(--${a[1]})`;
  if (!COLOR.test(v) && !/^[0-9a-z ,.()%#-]+$/i.test(v)) throw new Error(`unsupported value: ${v}`);
  return v;
};

const themed = [...t.color.tokens, ...(t.shadow?.tokens ?? [])];
const block = (theme) =>
  themed
    .map((tok) => [tok.name, valueFor(tok, theme)])
    .filter(([, v]) => v !== undefined)
    .map(([n, v]) => `  --${n}: ${css(v)};`)
    .join('\n');

const out = [];
out.push('/* GENERATED by scripts/sync-design.mjs from design/tokens.json (SUBoard Spectrum design system). Do not edit. */');
for (const f of t.type.fonts ?? []) {
  const file = f.file.replace(/^fonts\//, '');
  out.push(`@font-face {\n  font-family: '${f.family}';\n  src: url('../assets/fonts/${file}') format('woff2');\n  font-weight: ${f.weight};\n  font-style: ${f.style ?? 'normal'};\n  font-display: swap;\n}`);
}
out.push(`:root, [data-theme="${first}"] {\n${block(first)}\n  color-scheme: light;\n}`);
for (const th of themes.slice(1)) {
  out.push(`[data-theme="${th}"] {\n${block(th)}\n  color-scheme: ${th === 'dark' ? 'dark' : 'light'};\n}`);
}
// Before the app sets data-theme (first paint), follow the OS preference for dark.
if (themes.includes('dark')) out.push(`@media (prefers-color-scheme: dark) {\n  :root:not([data-theme]) {\n${block('dark').replace(/^/gm, '  ')}\n    color-scheme: dark;\n  }\n}`);
const plain = Object.entries(t)
  .filter(([k, v]) => !['name', 'version', 'color', 'type', 'shadow'].includes(k) && v && Array.isArray(v.tokens))
  .flatMap(([, v]) => v.tokens.map((tok) => `  --${tok.name}: ${tok.value};`));
const families = Object.entries(t.type.families).map(([k, v]) => `  --font-${k}: ${v};`);
out.push(`:root {\n${[...plain, ...families].join('\n')}\n}`);
for (const g of t.type.groups)
  for (const s of g.styles)
    out.push(`.${s.name} {\n  font-family: var(--font-${s.family ?? g.family});\n  font-size: ${s.fontSize};\n  line-height: ${s.lineHeight};\n  font-weight: ${s.fontWeight};\n  letter-spacing: ${s.letterSpacing ?? 0};\n}`);

writeFileSync(join(styles, 'tokens.css'), out.join('\n') + '\n');
writeFileSync(
  join(styles, 'global.css'),
  '/* Copied verbatim by scripts/sync-design.mjs from design/bundle.css (SUBoard Spectrum design system). Do not edit here: change the design system and re-sync. */\n' +
    readFileSync(join(design, 'bundle.css'), 'utf8'),
);
mkdirSync(fontsOut, { recursive: true });
for (const f of readdirSync(design).filter((n) => n.endsWith('.woff2'))) copyFileSync(join(design, f), join(fontsOut, f));
console.log(`tokens.css: ${themed.length} themed tokens × ${themes.length} themes, ${plain.length} scalar tokens; global.css and fonts copied.`);
